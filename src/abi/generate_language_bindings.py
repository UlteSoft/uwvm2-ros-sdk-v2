#!/usr/bin/env python3
"""Generate raw language modules and linker fixtures from the committed scene contract."""
import argparse
import json
import sys
from pathlib import Path

sys.dont_write_bytecode = True
from language_contract import comment, domains
from ecmascript_bindings import render as ecmascript
from wat_bindings import render as wat

ROOT = Path(__file__).resolve().parents[2]
PUBLIC = Path("include/u2rosv2/universal/as/uwrosv2")
FIXTURE = Path("src/compilers/as/fixtures/all_imports.ts")
MARKER = "Generated by src/abi/generate_language_bindings.py."


def label(row):
    return "wr_" + row["name"].replace(".", "_")


def assemblyscript(contract):
    grouped = domains(contract)
    files = {}
    barrel = []
    fixture = ['/** Link-only fixture. Every export forwards its raw operands to the registered host import. */']
    wrappers = []
    for domain, rows in grouped.items():
        body = [f"/** Raw {domain.replace('_', ' ')} imports from {contract['module']}. */"]
        barrel.append(f'export * from "./{domain}";')
        fixture.append(f'import * as {domain}_abi from "./uwrosv2/{domain}";')
        for row in rows:
            args = ", ".join(f"{p['name']}: u{p['type'][1:]}" for p in row["parameters"])
            name = label(row)
            body += [comment(row) + f'\n@external("{contract["module"]}", "{row["name"]}")\n'
                     + f"export declare function {name}({args}): u32;"]
            actual = ", ".join(p["name"] for p in row["parameters"])
            wrappers.append(f"export function link_{name}({args}): u32 {{\n  return {domain}_abi.{name}({actual});\n}}")
        files[PUBLIC / (domain + ".ts")] = "\n\n".join(body)
    files[PUBLIC / "scene.ts"] = "/** All raw scene imports, grouped by domain. */\n" + "\n".join(barrel)
    statuses = ["/** Scene carrier status values. The abi import returns the major ABI on success. */"]
    for name, number in contract["statuses"].items():
        statuses.append(f"export const {name.upper()}: u32 = {number};")
    files[PUBLIC / "status.ts"] = "\n".join(statuses)
    files[FIXTURE] = "\n".join(fixture) + "\n\n" + "\n\n".join(wrappers)
    return {path: "// " + MARKER + "\n" + value.rstrip() + "\n" for path, value in files.items()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    contract = json.loads((ROOT / "src/abi/contract.json").read_bytes())
    files = {**assemblyscript(contract), **ecmascript(contract), **wat(contract)}
    changed = []
    for path, contents in files.items():
        target = ROOT / path
        if target.is_file() and target.read_text() == contents:
            continue
        changed.append(str(path))
        if not args.check:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(contents)
    for target in (ROOT / PUBLIC).glob("*.ts"):
        if target.relative_to(ROOT) not in files and MARKER in target.read_text().splitlines()[0]:
            changed.append(str(target.relative_to(ROOT)))
            if not args.check:
                target.unlink()
    if args.check and changed:
        parser.exit(1, "Binding drift:\n" + "\n".join(changed) + "\n")
    print(f"{len(contract['operations'])} imports across {len(domains(contract))} domains")


if __name__ == "__main__":
    main()
