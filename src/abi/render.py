"""Render independent language declarations from the checked VM tuple."""

from collections import defaultdict
from pathlib import Path
from language_contract import comment
from local import facade, scoped_enum

MARKER = "Generated by src/abi/generate.py"
SPECIAL = {"abi", "capability.open", "capability.close"}
OBSERVERS = {"permission", "modules", "vm"}
ROOT_C = Path("include/u2rosv2/universal/c/uwrosv2")
ROOT_CPP = Path("include/u2rosv2/universal/c++/uwrosv2")
ROOT_RS = Path("include/u2rosv2/universal/rust/uwrosv2/src")


def label(op):
    return op["name"].replace(".", "_")


def member(op):
    return op["name"].removeprefix("module.call." if op["domain"] == "module_call"
                                    else op["name"].split(".")[0] + ".").replace(".", "_")


def raw_c_name(op):
    return "uwrosv2_raw_" + label(op)


def raw_c_params(op, cpp=False):
    return ", ".join(f"uint{p['type'][1:]}_t {p['name']}" for p in op["parameters"]) or ("" if cpp else "void")


def c_raw(op, cpp):
    name = raw_c_name(op)
    args = raw_c_params(op, cpp)
    link = 'extern "C" UWROSV2_CPP_IMPORT' if cpp else "UWROSV2_C_LINK UWROSV2_C_IMPORT"
    end = "UWROSV2_CPP_NOEXCEPT" if cpp else "UWROSV2_C_NOEXCEPT"
    return f'{comment(op, style="doxygen")}\n{link}("{op["name"]}")\nuint32_t {name}({args}) {end};'


def rs_raw(op):
    args = ", ".join(f"{p['name']}: u{p['type'][1:]}" for p in op["parameters"])
    return f'{comment(op, style="rustdoc")}\n#[link_name = "{op["name"]}"]\npub fn {member(op)}({args}) -> u32;'


def record_wrapper(op, lang):
    """All ordinary VM carriers finish synchronously. Module exchange retains guest storage."""
    if op["name"] in SPECIAL or op["domain"] == "module_call":
        return ""
    observe = op["domain"] in OBSERVERS
    cap = "0" if observe else "cap.id"
    desc = "Invoke " + op["name"] + " with an encoded request and caller-owned result storage in guest memory zero."
    if lang == "c":
        decl = "" if observe else "uwrosv2_capability cap, "
        return f"""/** {desc} */
static inline uwrosv2_transfer uwrosv2_{label(op)}_record(
    {decl}uwrosv2_input request, uwrosv2_output output) UWROSV2_C_NOEXCEPT {{
    uint8_t length[8] = {{0}};
    if ((request.size && !request.data) || (output.size && !output.data))
        return uwrosv2_transfer_result(22, 0, output.size);
    uint32_t code = {raw_c_name(op)}({cap}, 0, uwrosv2_address(request.data),
        request.size, uwrosv2_address(output.data), output.size, uwrosv2_address(length));
    return uwrosv2_transfer_result(code, uwrosv2_read_le64(length), output.size);
}}"""
    if lang == "cpp":
        decl = "" if observe else "capability_handle cap, "
        return f"""/** {desc} */
UWROSV2_CPP_NODISCARD inline transfer {member(op)}_record({decl}input request, output reply) UWROSV2_CPP_NOEXCEPT {{
    uint8_t length[8] = {{0}};
    if ((request.size && !request.data) || (reply.size && !reply.data)) return detail::finish(22, 0, 0);
    const uint32_t code = raw::{raw_c_name(op)}({cap}, 0, detail::address(request.data),
        request.size, detail::address(reply.data), reply.size, detail::address(length));
    return detail::finish(code, detail::read_word(length), reply.size);
}}"""
    decl = "" if observe else "cap: &crate::Capability, "
    cap = "0" if observe else "cap.id()"
    return f"""/// {desc}
pub fn {member(op)}_record({decl}request: &[u8], output: &mut [u8]) -> crate::Result<usize> {{
    use crate::base::{{address, finish}};
    let mut length = [0u8; 8];
    // The three distinct borrows cover this synchronous call. The VM copies the request.
    let code = unsafe {{
        ffi::{member(op)}({cap}, 0, address(request.as_ptr()), request.len() as u64,
            address(output.as_mut_ptr()), output.len() as u64, address(length.as_mut_ptr()))
    }};
    finish(code, length, output.len())
}}"""


def status_header(statuses, lang):
    if lang == "c":
        values = [f"    UWROSV2_{name.upper()} = {value}" for name, value in statuses.items()]
        return "#pragma once\n/** The VM's scene carrier status codes. */\nenum uwrosv2_status {\n" + ",\n".join(values) + "\n};"
    if lang == "cpp":
        return ('#pragma once\n#include <stdint.h>\nnamespace uwrosv2 {\n'
                + scoped_enum("status", "uint32_t", statuses) + "\n}")
    return "//! The VM's scene carrier status codes.\n" + "\n".join(
        f"pub const {name.upper()}: u32 = {value};" for name, value in statuses.items())


def render(contract):
    domains = defaultdict(list)
    for op in contract["operations"]:
        domains[op["domain"]].append(op)
    outputs = {}
    for language, root, ext in (("c", ROOT_C, "h"), ("cpp", ROOT_CPP, "hpp"), ("rs", ROOT_RS, "rs")):
        outputs[root / f"status.{ext}"] = status_header(contract["statuses"], language)
    for domain, ops in sorted(domains.items()):
        c = ['#pragma once', '#include "wire.h"', '#include "status.h"']
        cpp = ['#pragma once', '#include "wire.hpp"', '#include "status.hpp"', f'namespace uwrosv2 {{ namespace {domain} {{', 'namespace raw {']
        if domain in {"clock", "guard", "timer", "wait"}:
            cpp.insert(3, '#include "owner.hpp"')
        rs = [f"//! Guest calls in the {domain.replace('_', ' ')} domain.", "pub mod ffi {",
              '    #[cfg_attr(target_family = "wasm", link(wasm_import_module = "' + contract["module"] + '"))]',
              '    extern "C" {']
        for op in ops:
            c.append(c_raw(op, False))
            cpp.append(c_raw(op, True))
            rs.append("\n".join("        " + line for line in rs_raw(op).splitlines()))
        cpp.append("} // namespace raw")
        rs.extend(["    }", "}"])
        for op in ops:
            c.append(record_wrapper(op, "c"))
            cpp.append(record_wrapper(op, "cpp"))
            rs.append(record_wrapper(op, "rs"))
        cpp.append(f"}} }} // namespace uwrosv2::{domain}")
        if domain in {"capability", "guard", "resource", "clock", "timer", "wait"}:
            c.append(facade(domain, ops, "c"))
            cpp.append(facade(domain, ops, "cpp"))
            rs.append(facade(domain, ops, "rs"))
        outputs[ROOT_C / f"{domain}.h"] = "\n\n".join(s for s in c if s)
        outputs[ROOT_CPP / f"{domain}.hpp"] = "\n\n".join(s for s in cpp if s)
        outputs[ROOT_RS / f"{domain}.rs"] = "\n\n".join(s for s in rs if s)
    for root, ext in ((ROOT_C, "h"), (ROOT_CPP, "hpp")):
        outputs[root / f"scene.{ext}"] = "/** @file Public guest scene interface. */\n#pragma once\n" + "\n".join(
            f'#include "{domain}.{ext}"' for domain in sorted(domains))
    outputs[ROOT_CPP / "scene.hpp"] += '\n#include "owner.hpp"'
    outputs[ROOT_RS / "lib.rs"] = (
        "#![no_std]\n//! Guest bindings for the uwvm_ros_v2 scene module. Each domain owns its Wasm imports.\n"
        "//! The slice-based API uses memory zero. The ffi modules take an explicit memory index and 64-bit offsets.\n"
        "//! Exchange operations can retain and erase guest storage. See their individual safety contracts.\n"
        "mod base;\npub use base::{Capability, Error, Resource, Result};\npub use capability::abi;\n"
        "pub mod status;\npub mod wire;\n" + "\n".join(f"pub mod {domain};" for domain in sorted(domains)))
    return {p: f"// {MARKER}. Edit its input or renderer to update this file.\n{body.rstrip()}\n"
            for p, body in outputs.items()}
