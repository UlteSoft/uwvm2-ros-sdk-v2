"""Render the QuickJS-backed raw ES modules and the matching TypeScript declarations."""
from pathlib import Path
from language_contract import comment, domains

PREFIX = Path("include/u2rosv2/universal")
MARKER = "// Generated by src/abi/generate_language_bindings.py.\n"


def render(contract):
    files = {}
    groups = domains(contract)
    for domain, rows in groups.items():
        js = [f"/** Raw {domain.replace('_', ' ')} imports from {contract['module']}. */"]
        ts = js.copy()
        for row in rows:
            name = "wr_" + row["name"].replace(".", "_")
            args = ", ".join(p["name"] for p in row["parameters"])
            types = ", ".join(f"{p['name']}: {'bigint' if p['type'] == 'i64' else 'number'}" for p in row["parameters"])
            doc = comment(row, style="typescript")
            js.append(f'{comment(row, style="javascript")}\nexport function {name}({args}) {{\n  return globalThis.wros.raw["{row["name"]}"]({args});\n}}')
            ts.append(f"{doc}\nexport declare function {name}({types}): number;")
        files[PREFIX / "js/uwrosv2" / (domain + ".mjs")] = MARKER + "\n\n".join(js) + "\n"
        files[PREFIX / "typescript/uwrosv2" / (domain + ".d.ts")] = MARKER + "\n\n".join(ts) + "\n"
    for lang, suffix in (("js", ".mjs"), ("typescript", ".d.ts")):
        status = ["/** Carrier status codes. The abi import returns its major version on success. */"]
        for name, value in contract["statuses"].items():
            status.append(f"export const {name.upper()} = {value};" if lang == "js" else
                          f"export declare const {name.upper()}: {value};")
        files[PREFIX / lang / "uwrosv2" / ("status" + suffix)] = MARKER + "\n".join(status) + "\n"
    exports = "\n".join(f'export * from "uwrosv2/{domain}";' for domain in (*groups, "memory", "status"))
    files[PREFIX / "js/uwrosv2.mjs"] = (MARKER + "/** Named raw operations and the original managed script API. */\n"
        + "const scene = globalThis.wros;\nexport {scene};\nexport default scene;\n" + exports + "\n")
    files[PREFIX / "typescript/uwrosv2.d.ts"] = (MARKER + "/** Named raw operations and the original managed script API. */\n"
        + "declare const scene: typeof wros;\nexport {scene};\nexport default scene;\n" + exports + "\n")
    return files
