"""Render GNUstep class methods, documentation and implementations from the registered scene ABI."""
import json
from pathlib import Path

from language_contract import comment, domains

ROOT = Path(__file__).resolve().parents[2]
PUBLIC = ROOT / "include/u2rosv2/universal/objc/uwrosv2/objc"
SOURCES = ROOT / "src/runtimes/objc/bindings"
NOTICE = "// Generated by src/abi/generate_objc.py from the registered uwvm_ros_v2 operations."


def words(name):
    return name.replace(".", "_").split("_")


def camel(parts):
    return parts[0] + "".join(p.capitalize() for p in parts[1:])


def declaration(op):
    name = op["name"]
    if name.startswith("module.call."):
        name = name.removeprefix("module.call.")
    else:
        name = name.partition(".")[2] or name
    first = camel(words(name))
    components, arguments = [], []
    for idx, param in enumerate(op["parameters"]):
        label = first if idx == 0 else camel(words(param["name"]))
        variable = "handle" if param["name"] == "id" else param["name"]
        components.append(f"{label}:(uint{param['type'][1:]}_t){variable}")
        arguments.append(variable)
    selector = " ".join(components) if components else first
    return "+ (uint32_t)" + selector, ", ".join(arguments)


def main():
    contract = json.loads((ROOT / "src/abi/contract.json").read_bytes())
    PUBLIC.mkdir(parents=True, exist_ok=True)
    SOURCES.mkdir(parents=True, exist_ok=True)
    headers = []
    for domain, operations in domains(contract).items():
        name = {"qos": "QoS", "vm": "VM"}.get(domain) or "".join(p.capitalize() for p in words(domain))
        headers.append(name)
        cls = "UWR" + name
        interface = [NOTICE, "#pragma once", '#include "Object.h"', "",
                     f"/** The {domain.replace('_', ' ')} operations in the registered Wasm scene interface. */",
                     f"@interface {cls} : UWRObject"]
        body = [NOTICE, f"#include <uwrosv2/objc/{name}.h>", f"#include <uwrosv2/{domain}.h>", "",
                f"@implementation {cls}"]
        for op in operations:
            method, args = declaration(op)
            interface.extend(["", comment(op, style="doxygen").replace("@param id ", "@param handle "),
                              method + " __attribute__((objc_direct));"])
            raw = "uwrosv2_raw_" + op["name"].replace(".", "_")
            body.extend([method + " {", f"    return {raw}({args});", "}", ""])
        (PUBLIC / (name + ".h")).write_text("\n".join([*interface, "@end", ""]))
        (SOURCES / (name + ".m")).write_text("\n".join([*body, "@end", ""]))
    (PUBLIC / "Scene.h").write_text("\n".join([NOTICE, "#pragma once",
                                            *[f'#include "{name}.h"' for name in headers], ""]))


if __name__ == "__main__":
    main()
