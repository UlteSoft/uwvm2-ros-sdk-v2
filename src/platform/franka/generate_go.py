"""Emit Go/TinyGo public packages from the same pinned ROS 2 schema as the native Franka bindings."""
from collections import defaultdict
from functools import cache
import json
from pathlib import Path
import re
import subprocess
import textwrap

from generate_cdr import PUBLIC, field_doc, protocols, record_doc, save, upstream_licenses
from schema import HERE, PRIMITIVES, UPSTREAM, read_records, traits


DEST = PUBLIC / "go/cdr"
MODULE = "github.com/UlteSoft/uwvm2-ros-sdk-v2/franka/cdr"
BANNER = "// Code generated by src/platform/franka/generate_go.py from pinned ROS 2 inputs. DO NOT EDIT."
PACKAGES = {
    "franka_msgs": "describes the arm state published by franka_semantic_components, gripper actions, "
                   "joint-space point-to-point motion, impedance, frame and payload services.",
    "franka_spine_msgs": "describes the spine position and state topics, travel parameters, controller services "
                         "and the MoveAbsolute action with its ROS 2 protocol envelopes.",
    "action_msgs": "provides the goal identity, status list and cancellation service shared by ROS 2 actions.",
    "builtin_interfaces": "provides the signed seconds and unsigned nanoseconds of Jazzy ROS time.",
    "geometry_msgs": "describes vectors, points, orientations, poses, twists, accelerations, wrenches and "
                     "inertias embedded by the Franka state translation, together with their stamped forms.",
    "sensor_msgs": "represents timestamped joint names, positions, velocities and efforts used in Franka arm state.",
    "service_msgs": "identifies a Jazzy service event by its event kind, timestamp, client GID and sequence number.",
    "std_msgs": "provides the timestamp and reference frame attached to Franka and standard messages.",
    "unique_identifier_msgs": "provides the sixteen octets identifying a ROS 2 action goal.",
}
PRIMITIVE_TYPES = {**{name: name for name in PRIMITIVES}, "char": "uint8"}
WORDS = {"id": "ID", "uuid": "UUID", "gid": "GID", "tcp": "TCP", "ee": "EE"}


def pkg(name):
    return name.replace("_", "")


def identifier(name):
    return "".join(WORDS.get(word, word.capitalize()) for word in name.lower().split("_"))


def go_name(key, domain):
    if key in PRIMITIVES:
        return PRIMITIVE_TYPES[key]
    source, _, name = key.split("/")
    prefix = "" if source == domain else pkg(source) + "."
    return prefix + name.replace("_", "")


def comment(doc, indent=""):
    return [indent + "// " + line for line in textwrap.wrap(
        " ".join(doc.split()), width=96-len(indent), break_long_words=False, break_on_hyphens=False)]


def write_go(path, lines):
    formatted = subprocess.check_output(["gofmt"], input="\n".join(lines) + "\n", text=True)
    save(path, formatted)


def traversal(f, domain, minimum):
    field = "v." + identifier(f.name)
    typ = go_name(f.base, domain)
    primitive = f.base in PRIMITIVES
    method = typ.capitalize() if primitive else "CDRFields"
    if f.form in ("sequence", "bounded"):
        bound = str(f.count) if f.form == "bounded" else "cdr.Unbounded"
        min_size = str(minimum(f.base)) if primitive else typ + "MinPayloadSize"
        visit = f"func(item *{typ}, s *cdr.Stream) {{ s.{method}(item) }}" if primitive else f"(*{typ}).CDRFields"
        return [f"\tcdr.Sequence(s, &{field}, {bound}, {min_size}, {visit})"]
    value = field if f.form == "single" else field + "[i]"
    step = f"s.{method}(&{value})" if primitive else value + ".CDRFields(s)"
    return ["\t" + step] if f.form == "single" else [f"\tfor i := range {field} {{", "\t\t" + step, "\t}"]


def default_constructor(rec, domain, has_default):
    name = go_name(rec.name, domain)
    doc = f"// Default{name} applies ROS declaration defaults, including those in nested records."
    if not has_default(rec.name):
        return [doc, f"func Default{name}() {name} {{ return {name}{{}} }}", ""]
    lines = [doc, f"func Default{name}() {name} {{", f"\tvar v {name}"]
    for f in rec.fields:
        field = "v." + identifier(f.name)
        if f.default and float(f.default) != 0:
            lines.append(f"\t{field} = {f.default}")
        elif f.form in ("single", "fixed") and has_default(f.base):
            prefix, sep, typ = go_name(f.base, domain).rpartition(".")
            construct = prefix + sep + "Default" + typ + "()"
            if f.form == "single":
                lines.append(f"\t{field} = {construct}")
            else:
                lines += [f"\tfor i := range {field} {{", f"\t\t{field}[i] = {construct}", "\t}"]
    return [*lines, "\treturn v", "}", ""]


def record(rec, domain, notes, minimum, has_default):
    name = go_name(rec.name, domain)
    visit = f"(*{name}).CDRFields"
    lines = [f"// {name}Type is the full ROS 2 type identifier for this wire record.",
             f'const {name}Type = "{rec.name}"', "",
             f"// {name}MinPayloadSize is the lower bound on serialized field bytes, excluding padding and the header.",
             f"const {name}MinPayloadSize = {minimum(rec.name)}", ""]
    for key, base, value, doc in rec.constants:
        symbol = name + identifier(key)
        lines.extend(comment(f"{symbol} is {rec.name}.{key}. {doc}"))
        lines += [f"const {symbol} {go_name(base, domain)} = {value}", ""]
    lines.extend(comment(f"{name} represents {record_doc(rec, notes)}"))
    lines.append(f"type {name} struct {{")
    for f in rec.fields:
        typ = go_name(f.base, domain)
        shape = f"[{f.count}]" if f.form == "fixed" else "[]" if f.form in ("sequence", "bounded") else ""
        lines.extend(comment(field_doc(f, owned=True), "\t"))
        lines.append(f'\t{identifier(f.name)} {shape}{typ} `ros:"{f.name}" json:"{f.name}"`')
    lines += ["}", "", *default_constructor(rec, domain, has_default),
              "// ROS2Type returns the fully qualified ROS 2 record name.",
              f"func (*{name}) ROS2Type() string {{ return {name}Type }}", "",
              "// CDRFields visits this record in declaration order using the enclosing payload's alignment origin.",
              f"func (v *{name}) CDRFields(s *cdr.Stream) {{"]
    for f in rec.fields:
        lines.extend(traversal(f, domain, minimum))
    lines += ["}", "", "// CDRSize measures the complete encapsulated frame.",
              f"func (v *{name}) CDRSize() (int, error) {{ return cdr.Size(v, {visit}) }}", "",
              "// MarshalCDR writes to dst in the requested byte order after checking lengths and buffer capacity.",
              f"func (v *{name}) MarshalCDR(order cdr.Endian, dst []byte) (int, error) {{",
              f"\treturn cdr.MarshalTo(v, order, dst, {visit})", "}", "",
              "// MarshalBinary implements encoding.BinaryMarshaler and returns an owned little-endian frame.",
              f"func (v *{name}) MarshalBinary() ([]byte, error) {{ return cdr.Marshal(v, cdr.LittleEndian, {visit}) }}", "",
              f"// Validate{name} checks exactly one encapsulated sample, including every nested field.",
              f"func Validate{name}(src []byte) error {{ return cdr.Validate(src, {visit}) }}", "",
              "// UnmarshalCDR reads either byte order. Success replaces v with values independent of src.",
              f"func (v *{name}) UnmarshalCDR(src []byte) error {{ return cdr.Unmarshal(src, v, {visit}) }}", "",
              "// UnmarshalBinary implements encoding.BinaryUnmarshaler for complete encapsulated frames.",
              f"func (v *{name}) UnmarshalBinary(src []byte) error {{ return v.UnmarshalCDR(src) }}", ""]
    return lines


def main():
    records = read_records()
    notes = json.loads((HERE / "field_notes.json").read_bytes())
    upstream = json.loads((UPSTREAM / "sources.json").read_bytes())
    sources = {item["path"]: item for item in upstream["files"]}
    minimum, _ = traits(records)

    @cache
    def has_default(base):
        return base not in PRIMITIVES and any((f.default and float(f.default) != 0) or
                    (f.form in ("single", "fixed") and has_default(f.base)) for f in records[base].fields)

    save(DEST / "UPSTREAM-LICENSES.txt", upstream_licenses())
    groups = defaultdict(list)
    for rec in records.values():
        groups[rec.source].append(rec)
    for domain, description in PACKAGES.items():
        package = pkg(domain)
        write_go(DEST / package / "doc.go", [BANNER, "", *comment(f"Package {package} {description}"), f"package {package}"])
    for source, group in groups.items():
        domain, _, filename = source.split("/")
        package = pkg(domain)
        entry = sources[source]
        repo = upstream["repositories"][entry["repository"]]
        url = f"{repo['url']}/blob/{repo['commit']}/{entry['upstream_path']}"
        lines = [BANNER, "// Interface and field documentation are adapted from the upstream ROS 2 declarations and libfranka.",
                 "// Libfranka field documentation copyright (c) 2023 Franka Robotics GmbH. See ../UPSTREAM-LICENSES.txt.",
                 "// Declaration at " + url, "", f"package {package}", "", "import (", f'\t"{MODULE}"']
        deps = {f.base.split("/")[0] for rec in group for f in rec.fields if f.base not in PRIMITIVES}
        lines.extend(f'\t"{MODULE}/{pkg(dep)}"' for dep in sorted(deps - {domain}))
        lines += [")", ""]
        services, actions = protocols(group)
        for key in [*services, *actions]:
            name = go_name(key, domain)
            kind = "service" if key in services else "action"
            lines += [f"// {name}Type identifies the ROS 2 {kind} whose component records follow.",
                      f'const {name}Type = "{key}"', ""]
        for rec in group:
            lines.extend(record(rec, domain, notes, minimum, has_default))
        stem = re.sub(r"([A-Z])([A-Z][a-z])", r"\1_\2", Path(filename).stem)
        stem = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", stem).lower()
        write_go(DEST / package / (stem + ".go"), lines)


if __name__ == "__main__":
    main()
