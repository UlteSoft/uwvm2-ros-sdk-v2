def examples_and_observations():
    spec = json.loads((HERE.parent / "observations.json").read_bytes())["franka"]
    record = Observation("franka", spec)
    generate_observations(record)
    examples = HERE.parents[2] / "src/examples/franka"
    note = "Independent Fast-CDR v2.2.5 XCDRv1 output from src/platform/franka/elbow_fixtures.json."
    native = ["/* " + note + " */", "#ifndef FRANKA_EXAMPLE_ELBOW_FRAMES_H",
              "#define FRANKA_EXAMPLE_ELBOW_FRAMES_H", "#include <stdint.h>", ""]
    rust = ["// " + note, ""]
    for big in (False, True):
        data = record.example(big_cdr=big)
        name = "elbow_be" if big else "elbow_le"
        native += [f"static const uint8_t {name}[] = {{", octets(data), "};", ""]
        rust += [f"pub const {name.upper()}: &[u8] = &[", octets(data), "];", ""]
    for language in ("c", "cpp"):
        save(examples / language / "cdr/elbow_frames.h", "\n".join([*native, "#endif", ""]))
    save(examples / "rust/cdr/elbow_frames.rs", "\n".join(rust))


def main():
    records = read_records()
    notes = json.loads((HERE / "field_notes.json").read_bytes())
    minimum, borrows = traits(records)
    @cache
    def has_defaults(key):
        return key not in PRIMITIVES and any((f.default and float(f.default) != 0) or
                (f.form in ("single", "fixed") and has_defaults(f.base)) for f in records[key].fields)

    packages = defaultdict(list)
    for rec in records.values():
        packages[rec.name.split("/")[0]].append(rec)
    seq_bases = {f.base for rec in records.values() for f in rec.fields if f.form in ("sequence", "bounded")}
    save(C_DIR / "wire.h", native_wire(False))
    save(CPP_DIR / "wire.hpp", native_wire(True))
    seq_header = ["#ifndef UWROSV2_FRANKA_CDR_SEQUENCES_H", "#define UWROSV2_FRANKA_CDR_SEQUENCES_H",
                  '#include "wire.h"', ""]
    for base in sorted(seq_bases & PRIMITIVES.keys()):
        seq_header += [c_sequence(base, minimum), ""]
    save(C_DIR / "sequences.h", "\n".join([*seq_header, "#endif", ""]))
    for pkg, group in packages.items():
        deps = sorted({f.base.split("/")[0] for rec in group for f in rec.fields if f.base not in PRIMITIVES} - {pkg})
        for cpp, ext, directory in [(False, "h", C_DIR), (True, "hpp", CPP_DIR)]:
            guard = f"UWROSV2_FRANKA_CDR_{pkg}_{ext}".upper()
            lines = [*comment(BANNER), "#ifndef " + guard, "#define " + guard,
                     '#include "codec.hpp"' if cpp else '#include "sequences.h"']
            lines.extend(f'#include "{dep}.{ext}"' for dep in deps)
            lines += [""]
            if cpp:
                lines += ["namespace uwrosv2 { namespace franka { namespace cdr {", ""]
            for rec in group:
                lines.extend(cpp_record(rec, notes, minimum, has_defaults) if cpp else
                             c_record(rec, notes, minimum, has_defaults, seq_bases))
            lines.extend(descriptors(group, cpp))
            if cpp:
                lines.append("} } } // namespace uwrosv2::franka::cdr")
            save(directory / f"{pkg}.{ext}", "\n".join([*lines, "#endif", ""]))
        lines = [*(line.replace("///", "//!", 1) for line in comment(BANNER, rust=True)), "use super::*;", ""]
        for rec in group:
            lines.extend(rust_record(rec, notes, minimum, borrows))
        lines.extend(rust_descriptors(group, borrows))
        save(PUBLIC / "rust/cdr" / f"{pkg}.rs", "\n".join(lines))
    for directory, ext in [(C_DIR, "h"), (CPP_DIR, "hpp")]:
        guard = f"UWROSV2_FRANKA_CDR_RECORDS_{ext}".upper()
        includes = [f'#include "{pkg}.{ext}"' for pkg in sorted(packages)]
        save(directory / f"records.{ext}", "\n".join([*comment(BANNER), "#ifndef " + guard, "#define " + guard,
                                                      *includes, "#endif", ""]))
    licenses = upstream_licenses()
    for directory in (C_DIR, CPP_DIR, PUBLIC / "rust/cdr"):
        save(directory / "UPSTREAM-LICENSES.txt", licenses)
    examples_and_observations()


if __name__ == "__main__":
    main()
