def save(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.is_file() or path.read_text() != content:
        path.write_text(content)


def substitute(template, **values):
    for name, value in values.items():
        template = template.replace("@" + name + "@", str(value))
    return template


def cpp_or_c_name(key, cpp):
    if key == "string":
        return "string" if cpp else P + "string"
    if cpp and key == "bool":
        return "bool"
    if key in C_TYPES:
        return C_TYPES[key]
    pkg, _, name = key.split("/")
    return pkg + "::" + name if cpp else P + pkg + "_" + name


def symbol(base, action):
    if base in PRIMITIVES:
        return P + action + "_" + ("uint8" if base == "char" else base)
    return cpp_or_c_name(base, False) + "_" + action


def sequence(base):
    return (P + base if base in PRIMITIVES else cpp_or_c_name(base, False)) + "_sequence"


def native_wire(cpp):
    p = "" if cpp else P
    nx = CPP_NX if cpp else C_NX
    guard = "UWROSV2_FRANKA_CDR_WIRE_" + ("HPP" if cpp else "H")
    lines = ["/** XCDRv1 PLAIN_CDR primitives. Generated by src/platform/franka/generate_cdr.py. */",
             "#ifndef " + guard, "#define " + guard, "#include <stddef.h>", "#include <stdint.h>",
             "#include <limits.h>", "#include <float.h>", "#include <string.h>", "",
             "#if defined(__cplusplus) && (__cplusplus >= 201103L || (defined(_MSVC_LANG) && _MSVC_LANG >= 201103L))",
             f"#define {nx} noexcept", "#elif defined(__cplusplus)", f"#define {nx} throw()",
             "#else", f"#define {nx}", "#endif", ""]
    if cpp:
        lines += ["namespace uwrosv2 { namespace franka { namespace cdr {", ""]
    lines += [substitute((HERE / "native_wire.inc").read_text(), p=p, NX=nx).rstrip(), ""]
    for base, width in PRIMITIVES.items():
        if base in ("string", "char"):
            continue
        t = cpp_or_c_name(base, cpp)
        word = f"uint{width * 8}_t"
        lines += [f"static inline int {p}get_{base}({p}reader *r, {t} *out) {nx} {{", "    uint64_t bits;",
                  f"    if (!{p}get_word(r, {width}, &bits)) return 0;"]
        if base == "bool":
            lines += ["    if (bits > 1) return 0;", "    *out = bits != 0;"]
        elif base.startswith("uint"):
            lines += [f"    *out = ({t})bits;"]
        else:
            lines += [f"    const {word} value = ({word})bits;", "    memcpy(out, &value, sizeof value);"]
        lines += ["    return 1;", "}", "", f"static inline int {p}put_{base}({p}writer *w, const {t} *value) {nx} {{"]
        if base == "bool":
            if not cpp:
                lines.append("    if (*value > 1) return 0;")
            expr = "*value ? 1u : 0u"
        elif base.startswith("uint"):
            expr = "*value"
        else:
            lines += [f"    {word} bits;", "    memcpy(&bits, value, sizeof bits);"]
            expr = "bits"
        lines += [f"    return {p}put_word(w, {width}, {expr});", "}", ""]
    if cpp:
        lines += ["template<class T> struct value_codec;", ""]
        for base, width in PRIMITIVES.items():
            if base == "char":
                continue
            t = cpp_or_c_name(base, True)
            lines += [f"template<> struct value_codec<{t}> {{", f"    enum {{ minimum_size = {width} }};",
                      f"    static bool get(reader *r, {t} *out) {nx} {{ return get_{base}(r, out) != 0; }}",
                      f"    static bool put(writer *w, const {t} *v) {nx} {{ return put_{base}(w, v) != 0; }}",
                      "};", ""]
        lines += ["} } } // namespace uwrosv2::franka::cdr"]
    return "\n".join([*lines, "#endif", ""])


def comment(text, indent="", rust=False):
    prefix = indent + ("/// " if rust else " * ")
    wrapped = textwrap.wrap(" ".join(text.split()), width=100-len(prefix), break_long_words=False, break_on_hyphens=False)
    lines = [prefix + line for line in wrapped]
    return lines if rust else [indent + "/**", *lines, indent + " */"]


def record_doc(rec, notes):
    source_name = str(Path(rec.source).with_suffix(""))
    suffix = rec.name[len(source_name):].lstrip("_")
    parts = [rec.name + ".", notes[source_name]["$type"]]
    if suffix:
        parts.append(ROLES[suffix])
    if rec.derived:
        parts.append("Layout derived by the pinned Jazzy rosidl parser.")
    return " ".join(parts)


def field_doc(f, *, owned=False):
    parts = [f.doc.strip()]
    if parts[0][-1] not in ".!?":
        parts[0] += "."
    if f.form == "fixed":
        parts.append(f"Exactly {f.count} elements in declaration order, with no count prefix.")
    elif f.form in ("sequence", "bounded"):
        size = f"at most {f.count}" if f.form == "bounded" else "a uint32 count of"
        storage = "Decoding creates an owned Go slice." if owned else "Decoded elements borrow the immutable input."
        parts.append(f"CDR sequence with {size} elements. {storage}")
    if f.base == "string":
        parts.append("The decoded Go string owns its content bytes and excludes the terminal NUL." if owned else
                     "String bytes exclude the CDR terminator and borrow the input after decoding.")
    if f.default:
        parts.append(f"Declared default {f.default}.")
    return " ".join(parts)


def c_sequence(base, minimum):
    return substitute((HERE / "c_sequence.inc").read_text(), p=P, NX=C_NX, label=base,
                      t=cpp_or_c_name(base, False), s=sequence(base), get=symbol(base, "get"),
                      put=symbol(base, "put"), min=minimum(base)).rstrip()


def native_fields(rec, cpp):
    lines = []
    for f in rec.fields:
        lines.extend(comment(field_doc(f), "    "))
        t = cpp_or_c_name(f.base, cpp)
        dim = ""
        if f.form in ("sequence", "bounded"):
            t = f"Sequence<{t}>" if cpp else sequence(f.base)
        elif f.form == "fixed":
            dim = f"[{f.count}]"
        lines.append(f"    {t} {f.name}{dim};")
    return lines


def default_body(rec, cpp, has_defaults, indent="    "):
    name = cpp_or_c_name(rec.name, cpp)
    init = name + "()" if cpp else "{0}"
    lines = [f"{indent}{name} value = {init};"]
    for f in rec.fields:
        if f.default and float(f.default) != 0:
            lines.append(f"{indent}value.{f.name} = {f.default};")
        if f.form in ("single", "fixed") and has_defaults(f.base):
            fn = cpp_or_c_name(f.base, cpp) + ("::defaults()" if cpp else "_defaults()")
            if f.form == "fixed":
                lines.append(f"{indent}for (size_t i = 0; i < {f.count}; ++i) value.{f.name}[i] = {fn};")
            else:
                lines.append(f"{indent}value.{f.name} = {fn};")
    return [*lines, indent + "return value;"]


def native_transfer(rec, cpp, action):
    r = action == "get"
    cursor = "r" if r else "w"
    false, true = ("false", "true") if cpp else ("0", "1")
    indent = "        " if cpp else "    "
    lines = []
    for f in rec.fields:
        t = cpp_or_c_name(f.base, cpp)
        member = "v->" + f.name
        if f.form in ("sequence", "bounded"):
            bound = str(f.count) if f.form == "bounded" else "(uint32_t)-1"
            if cpp:
                call = f"Sequence<{t}>::get(r, &{member}, {bound})" if r else f"{member}.put(w, {bound})"
            else:
                call = f"{sequence(f.base)}_{action}({cursor}, &{member}, {bound})"
        else:
            transfer = f"value_codec<{t}>::{action}" if cpp else symbol(f.base, action)
            if f.form == "fixed":
                lines += [f"{indent}for (size_t i = 0; i < {f.count}; ++i) {{",
                          f"{indent}    if (!{transfer}({cursor}, &{member}[i])) return {false};", indent + "}"]
                continue
            call = f"{transfer}({cursor}, &{member})"
        lines.append(f"{indent}if (!{call}) return {false};")
    return [*lines, indent + "return " + true + ";"]


def c_record(rec, notes, minimum, has_defaults, seq_bases):
    t = cpp_or_c_name(rec.name, False)
    lines = [*comment(record_doc(rec, notes)), "typedef struct {", *native_fields(rec, False),
             "} " + t + ";", f'#define {t}_DATATYPE "{rec.name}"', ""]
    for name, base, value, doc in rec.constants:
        lines += [*comment(doc + " Named constant, absent from the wire."),
                  f"#define {t}_{name} (({cpp_or_c_name(base, False)}){value})", ""]
    lines += [f"static inline {t} {t}_defaults(void) {C_NX} {{", *default_body(rec, False, has_defaults), "}", "",
              f"static inline int {t}_get({P}reader *r, {t} *v) {C_NX} {{",
              *native_transfer(rec, False, "get"), "}", "",
              f"static inline int {t}_put({P}writer *w, const {t} *v) {C_NX} {{",
              *native_transfer(rec, False, "put"), "}", "",
              substitute((HERE / "c_record_api.inc").read_text(), t=t, p=P, NX=C_NX).rstrip(), ""]
    if rec.name in seq_bases:
        lines += [c_sequence(rec.name, minimum), ""]
    return lines


def cpp_record(rec, notes, minimum, has_defaults):
    pkg, _, name = rec.name.split("/")
    t = cpp_or_c_name(rec.name, True)
    lines = [f"namespace {pkg} {{"]
    if rec.constants:
        lines += [f"namespace {name}_Constants {{"]
        for n, base, value, doc in rec.constants:
            lines += [*comment(doc + " Rosidl constant, occupying zero wire bytes."),
                      f"static const {cpp_or_c_name(base, True)} {n} = {value};"]
        lines += [f"}} // namespace {name}_Constants", ""]
    lines += [*comment(record_doc(rec, notes)), f"struct {name} {{"]
    for n, _, _, _ in rec.constants:
        lines.append(f"    enum {{ {n} = {name}_Constants::{n} }};")
    lines += [*native_fields(rec, True), "",
              f'    static const char *datatype() {CPP_NX} {{ return "{rec.name}"; }}',
              f"    static {name} defaults() {CPP_NX} {{", *default_body(rec, True, has_defaults, "        "),
              "    }", "};", "} // namespace " + pkg, "",
              f"template<> struct value_codec<{t}> {{", f"    enum {{ minimum_size = {minimum(rec.name)} }};",
              f"    static bool get(reader *r, {t} *v) {CPP_NX} {{", *native_transfer(rec, True, "get"), "    }",
              f"    static bool put(writer *w, const {t} *v) {CPP_NX} {{", *native_transfer(rec, True, "put"),
              "    }", "};", ""]
    return lines


def protocols(records):
    """Name the service and action descriptors, including the two services of each action."""
    services, actions = [], []
    for source in sorted({rec.source for rec in records}):
        stem = str(Path(source).with_suffix(""))
        if source.endswith(".srv"):
            services.append(stem)
        elif source.endswith(".action"):
            actions.append(stem)
            services.extend([stem + "_SendGoal", stem + "_GetResult"])
    return services, actions


def descriptors(records, cpp):
    services, actions = protocols(records)
    lines = []
    for key in [*services, *actions]:
        pkg, _, name = key.split("/")
        service = key in services
        members = ["Request", "Response", "Event"] if service else ["Goal", "Result", "Feedback", "SendGoal", "GetResult", "FeedbackMessage"]
        kind = "Service" if service else "Action"
        if cpp:
            lines += [f"namespace {pkg} {{", *comment(f"{kind} {key}. Groups related protocol records."),
                      f"struct {name} {{"]
            lines.extend(f"    typedef {name}_{m} {m};" for m in members)
            lines += [f'    static const char *datatype() {CPP_NX} {{ return "{key}"; }}', "};", "}", ""]
        else:
            lines += [*comment(f"{kind} {key}. Append the rosidl component suffix for its payload records."),
                      f'#define {P}{pkg}_{name}_DATATYPE "{key}"', ""]
    return lines


def rust_type(base, borrows):
    if base in PRIMITIVES:
        return RUST_TYPES[base]
    pkg, _, name = base.split("/")
    return "super::" + pkg + "::" + name + ("<'a>" if borrows(base) else "")


def rust_record(rec, notes, minimum, borrows):
    name = rec.name.rsplit("/", 1)[1]
    decl = name + ("<'a>" if borrows(rec.name) else "")
    custom = any(f.default and float(f.default) != 0 for f in rec.fields)
    lines = [*comment(record_doc(rec, notes), rust=True), "#[derive(Clone, Copy" + ("" if custom else ", Default") + ")]",
             f"pub struct {decl} {{"]
    for f in rec.fields:
        t = rust_type(f.base, borrows)
        if f.form == "fixed":
            t = f"[{t}; {f.count}]"
        elif f.form in ("bounded", "sequence"):
            t = f"Sequence<'a, {t}>"
        lines += [*comment(field_doc(f), "    ", rust=True), f"    pub {f.name}: {t},"]
    lines += ["}", ""]
    if custom:
        lines += [f"impl Default for {name} {{", "    fn default() -> Self {", "        Self {"]
        for f in rec.fields:
            literal = str(float(f.default)) if f.default else "Default::default()"
            lines.append(f"            {f.name}: {literal},")
        lines += ["        }", "    }", "}", ""]
    if rec.constants:
        constants_type = name + ("<'_>" if borrows(rec.name) else "")
        lines.append(f"impl {constants_type} {{")
        for n, base, value, doc in rec.constants:
            lines += [*comment(doc + " Named constant, absent from the wire.", "    ", rust=True),
                      f"    pub const {n}: {RUST_TYPES[base]} = {value};"]
        lines += ["}", ""]
    lines += [f"impl<'a> CdrValue<'a> for {decl} {{", f"    const MIN_SIZE: usize = {minimum(rec.name)};",
              "    fn read(r: &mut Reader<'a>) -> Result<Self, Error> {", "        Ok(Self {"]
    for f in rec.fields:
        read = f"Sequence::read_bounded(r, {f.count})" if f.form == "bounded" else "CdrValue::read(r)"
        lines.append(f"            {f.name}: {read}?,")
    lines += ["        })", "    }", "    fn write(&self, w: &mut Writer<'_>) -> Result<(), Error> {"]
    for f in rec.fields:
        call = f"write_bounded(w, {f.count})" if f.form == "bounded" else "write(w)"
        lines.append(f"        self.{f.name}.{call}?;")
    lines += ["        Ok(())", "    }", "}", f"impl<'a> Message<'a> for {decl} {{",
              f"    const TYPE: &'static str = \"{rec.name}\";", "}", ""]
    return lines


def rust_descriptors(records, borrows):
    services, actions = protocols(records)
    lines = []
    for key in [*services, *actions]:
        name = key.rsplit("/", 1)[1]
        service = key in services
        kind = "Service" if service else "Action"
        lines += [*comment(f"{kind} {key}. Groups related protocol records.", rust=True), f"pub struct {name};",
                  f"impl {kind} for {name} {{", f"    const TYPE: &'static str = \"{key}\";"]
        for member in (["Request", "Response", "Event"] if service else ["Goal", "Result", "Feedback", "FeedbackMessage"]):
            t = name + "_" + member + ("<'a>" if borrows(key + "_" + member) else "")
            lines.append(f"    type {member}<'a> = {t};")
        if not service:
            lines += [f"    type SendGoal = {name}_SendGoal;", f"    type GetResult = {name}_GetResult;"]
        lines += ["}", ""]
    return lines


