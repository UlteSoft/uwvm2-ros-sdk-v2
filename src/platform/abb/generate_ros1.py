"""Generate the C, C++ and Rust body codecs from the pinned ABB ROS 1 interfaces."""
import json
import textwrap
from collections import defaultdict
from pathlib import Path

from ros1_schema import PRIMITIVES, fingerprints, load


HERE = Path(__file__).resolve().parent
PUBLIC = HERE.parents[2] / "include/u2rosv2/platform/abb"
PREFIX = "uwrosv2_abb_ros1_"
GENERATED = "Generated by src/platform/abb/generate_ros1.py from the pinned ROS 1 definitions."
C_TYPES = {"bool": "uint8_t", "uint8": "uint8_t", "uint16": "uint16_t", "uint32": "uint32_t",
           "float32": "float", "float64": "double", "string": PREFIX + "string", "time": PREFIX + "time"}
RUST_TYPES = {"bool": "bool", "uint8": "u8", "uint16": "u16", "uint32": "u32",
              "float32": "f32", "float64": "f64", "string": "&'a [u8]", "time": "Time"}


def minimum_sizes(records):
    sizes = {"bool": 1, "uint8": 1, "uint16": 2, "uint32": 4,
             "float32": 4, "float64": 8, "time": 8, "string": 4}
    for rec in records:
        sizes[rec.qualified] = sum(4 if field.array else sizes[field.type] for field in rec.fields)
    return sizes


def record_doc(record):
    if record.service:
        role = "Request" if record.name.endswith("Request") else "Response"
        identity = f"{role} body for `{record.package}/{record.service}`."
    else:
        identity = f"`{record.qualified}`."
    if not record.fields:
        identity += " The wire body occupies zero bytes."
    return identity + "\n\n" + record.description


def license_notice():
    license_file = HERE / "upstream/ros1/licenses/abb_interfaces_ros1/LICENSE"
    return "\n".join(["/*", " * ABB interface declarations and field descriptions",
                      *[(" * " + line).rstrip() for line in license_file.read_text().splitlines()],
                      " *", " * std_msgs/Header is from the ROS std_msgs package (BSD).", " */"])


def comment(doc, indent="", rust=False):
    if not doc:
        return []
    lines = []
    for paragraph in doc.split("\n\n"):
        if lines:
            lines.append("")
        if rust:
            # Unit annotations such as [mm] in .msg files are literal text.
            paragraph = paragraph.replace("[", "\\[").replace("]", "\\]")
        lines.extend(textwrap.wrap(paragraph, width=96 - len(indent), break_on_hyphens=False))
    if rust:
        return [(indent + "/// " + line).rstrip() for line in lines]
    if len(lines) == 1:
        return [f"{indent}/** {lines[0]} */"]
    return [indent + "/**", *[(indent + " * " + line).rstrip() for line in lines], indent + " */"]


def c_record(name):
    return PREFIX + name.replace("/", "_")


def c_type(field):
    base = C_TYPES[field.type] if field.type in PRIMITIVES else c_record(field.type)
    return base + ("_array" if field.array else "")


def c_operation(field, write):
    if field.type in PRIMITIVES:
        return PREFIX + ("put_" if write else "get_") + field.type
    return c_type(field) + ("_write" if write else "_read")


def c_metadata(name, digest):
    ident = c_record(name)
    return [f'/** ROS 1 datatype of `{name}`. */', f'#define {ident}_DATATYPE "{name}"',
            f'/** ROS 1 connection-header MD5 of `{name}`. */', f'#define {ident}_MD5 "{digest}"']


def c_records(records, hashes, minimum):
    lines = [f"/* {GENERATED} */", license_notice(), "#ifndef UWROSV2_ABB_ROS1_RECORDS_H",
             "#define UWROSV2_ABB_ROS1_RECORDS_H", '#include "wire.h"', ""]
    api = (HERE / "c_record_api.inc").read_text().rstrip()
    array = (HERE / "c_array.inc").read_text().rstrip()
    elements = {f.type for rec in records for f in rec.fields if f.array}
    for rec in records:
        name = c_record(rec.qualified)
        lines.append(f"/* {rec.qualified} */")
        if rec.service is None:
            lines.extend(c_metadata(rec.qualified, hashes[rec.qualified]))
        elif rec.name == rec.service + "Request":
            key = f"{rec.package}/{rec.service}"
            lines.extend(c_metadata(key, hashes[key]))
        for const in rec.constants:
            val = json.dumps(const.value) if const.type == "string" else const.value
            lines.extend(comment(const.description))
            lines.append(f"#define {name}_{const.name} {val}")
        lines += [*comment(record_doc(rec)), "typedef struct {"]
        for f in rec.fields:
            lines.extend(comment(f.description, "    "))
            lines.append(f"    {c_type(f)} {f.name};")
        if not rec.fields:
            lines.append("    uint8_t reserved; /* No wire bytes. */")
        lines += [f"}} {name};", "", "/** @cond INTERNAL */"]
        for write in (False, True):
            fn = "write" if write else "read"
            cursor = "writer" if write else "reader"
            qual = "const " if write else ""
            lines += [f"static inline int {name}_{fn}(",
                      f"    {PREFIX}{cursor} *stream, {qual}{name} *value) UWROSV2_ABB_ROS1_NOEXCEPT {{"]
            if rec.fields:
                calls = [c_operation(f, write) + f"(stream, &value->{f.name})" for f in rec.fields]
                lines.append("    return " + "\n        && ".join(calls) + ";")
            else:
                lines += ["    (void)stream;", "    (void)value;" if write else "    value->reserved = 0;", "    return 1;"]
            lines += ["}"]
        lines += ["/** @endcond */", "", api.replace("@TYPE@", name).replace("@QUALIFIED@", rec.qualified)]
        if rec.qualified in elements:
            lines += ["", array.replace("@TYPE@", name).replace("@QUALIFIED@", rec.qualified)
                      .replace("@MINIMUM@", str(minimum[rec.qualified]))]
        lines.append("")
    lines += ["#endif"]
    return "\n".join(lines) + "\n"


def cpp_type(field):
    types = dict(C_TYPES, bool="bool", string="String", time="Time")
    name = types.get(field.type, field.type.replace("/", "::"))
    return f"Sequence<{name}>" if field.array else name


def cpp_metadata(name, digest):
    return ['    /** ROS 1 connection-header datatype. */',
            f'    static const char *datatype() UWROSV2_ABB_ROS1_NOEXCEPT {{ return "{name}"; }}',
            '    /** ROS 1 connection-header type fingerprint. */',
            f'    static const char *md5() UWROSV2_ABB_ROS1_NOEXCEPT {{ return "{digest}"; }}']


def cpp_records(records, hashes, minimum):
    lines = [f"/* {GENERATED} */", license_notice(), "#ifndef UWROSV2_ABB_ROS1_RECORDS_HPP",
             "#define UWROSV2_ABB_ROS1_RECORDS_HPP", '#include "wire.hpp"', "",
             "namespace uwrosv2 { namespace abb { namespace ros1 {", ""]
    for rec in records:
        lines += [f"namespace {rec.package} {{", *comment(record_doc(rec)), f"struct {rec.name} {{"]
        for f in rec.fields:
            lines.extend(comment(f.description, "    "))
            lines.append(f"    {cpp_type(f)} {f.name};")
        lines.append("    /** Smallest valid body in bytes, with empty strings and sequences. */")
        lines.append(f"    enum {{ minimum_wire_size = {minimum[rec.qualified]} }};")
        if rec.service is None:
            lines.extend(cpp_metadata(rec.qualified, hashes[rec.qualified]))
        for const in rec.constants:
            lines.extend(comment(const.description, "    "))
            if const.type == "string":
                lines.append(f'    static const char *{const.name}() UWROSV2_ABB_ROS1_NOEXCEPT {{ return {json.dumps(const.value)}; }}')
            else:
                lines.append(f"    enum {{ {const.name} = {const.value} }};")
        lines += ["    /** @cond INTERNAL */", "    template<class Stream, class Value>"]
        if rec.fields:
            calls = (f"stream.field(value.{f.name})" for f in rec.fields)
            lines += ["    static bool fields(Stream &stream, Value &value) UWROSV2_ABB_ROS1_NOEXCEPT {",
                      "        return " + "\n            && ".join(calls) + ";"]
        else:
            lines += ["    static bool fields(Stream &, Value &) UWROSV2_ABB_ROS1_NOEXCEPT {", "        return true;"]
        lines += ["    }", "    /** @endcond */", "};"]
        if rec.service and rec.name == rec.service + "Response":
            key = f"{rec.package}/{rec.service}"
            lines += [*comment(f"Service `{key}`.\n\n" + rec.description), f"struct {rec.service} {{",
                      "    /** Serialized request body. */", f"    typedef {rec.service}Request Request;",
                      "    /** Serialized successful reply body. */", f"    typedef {rec.service}Response Response;",
                      *cpp_metadata(key, hashes[key]), "};"]
        lines += [f"}} // namespace {rec.package}", ""]
    lines += ["} } } // namespace uwrosv2::abb::ros1", "#endif"]
    return "\n".join(lines) + "\n"


def rust_borrows(records):
    borrows = {}
    for rec in records:
        borrows[rec.qualified] = any(f.array or f.type == "string" or borrows.get(f.type, False) for f in rec.fields)
    return borrows


def rust_type(field, package, borrows):
    if field.type in PRIMITIVES:
        name = RUST_TYPES[field.type]
    else:
        pkg, name = field.type.split("/")
        if pkg != package:
            name = f"super::{pkg}::{name}"
        if borrows[field.type]:
            name += "<'a>"
    return f"Sequence<'a, {name}>" if field.array else name


def rust_record(rec, borrows, minimum, hashes):
    package = rec.package
    slot = "<'a>" if borrows[rec.qualified] else ""
    name = rec.name + slot
    lines = [*comment(record_doc(rec), "    ", rust=True), "    #[derive(Debug, Clone, Copy, Default)]",
             f"    pub struct {name} {{"]
    for f in rec.fields:
        lines.extend(comment(f.description, "        ", rust=True))
        lines.append(f"        pub {f.name}: {rust_type(f, package, borrows)},")
    lines.append("    }")
    if rec.constants or rec.service is None:
        lines.append(f"    impl{slot} {name} {{")
        if rec.service is None:
            lines += ["        /// ROS 1 connection-header datatype.",
                      f'        pub const TYPE: &\'static str = "{rec.qualified}";',
                      "        /// ROS 1 connection-header type fingerprint.",
                      f'        pub const MD5: &\'static str = "{hashes[rec.qualified]}";']
        for c in rec.constants:
            lines.extend(comment(c.description, "        ", rust=True))
            if c.type == "string":
                lines.append(f"        pub const {c.name}: &'static str = {json.dumps(c.value)};")
            else:
                lines.append(f"        pub const {c.name}: {RUST_TYPES[c.type]} = {c.value};")
        lines.append("    }")
    cursor = "reader" if rec.fields else "_reader"
    writer = "writer" if rec.fields else "_writer"
    lines += [f"    impl<'a> Message<'a> for {name} {{", f"        const MIN_WIRE_SIZE: usize = {minimum[rec.qualified]};",
              f"        fn read({cursor}: &mut Reader<'a>) -> Result<Self, Error> {{", "            Ok(Self {"]
    for f in rec.fields:
        method = "boolean" if f.type == "bool" else f.type
        if f.array:
            call = "reader.sequence()"
        elif f.type in PRIMITIVES:
            call = f"reader.{method}()"
        else:
            call = "Message::read(reader)"
        lines.append(f"                {f.name}: {call}?,")
    lines += ["            })", "        }", f"        fn write(&self, {writer}: &mut Writer<'_>) -> Result<(), Error> {{"]
    for f in rec.fields:
        method = "boolean" if f.type == "bool" else f.type
        if f.array:
            call = f"writer.sequence(&self.{f.name})"
        elif f.type in PRIMITIVES:
            call = f"writer.{method}(self.{f.name})"
        else:
            call = f"self.{f.name}.write(writer)"
        lines.append(f"            {call}?;")
    lines += ["            Ok(())", "        }", "    }", ""]
    if rec.service and rec.name == rec.service + "Response":
        key = f"{package}/{rec.service}"
        req = rec.service + "Request" + ("<'a>" if borrows[key + "Request"] else "")
        lines += [*comment(f"Service `{key}`.\n\n" + rec.description, "    ", rust=True),
                  f"    pub struct {rec.service};", f"    impl Service for {rec.service} {{",
                  f'        const TYPE: &\'static str = "{key}";', f'        const MD5: &\'static str = "{hashes[key]}";',
                  f"        type Request<'a> = {req};", f"        type Response<'a> = {name};", "    }", ""]
    return lines


def rust_records(records, hashes, minimum):
    borrows = rust_borrows(records)
    packages = defaultdict(list)
    for rec in records:
        packages[rec.package].append(rec)
    lines = [f"// {GENERATED}", license_notice(), ""]
    for package, members in packages.items():
        lines += [f"pub mod {package} {{", "    use super::*;", ""]
        for rec in members:
            lines.extend(rust_record(rec, borrows, minimum, hashes))
        lines += ["}", ""]
    return "\n".join(lines)


def main():
    records = load()
    hashes, minimum = fingerprints(records), minimum_sizes(records)
    outputs = {"c/uwrosv2/abb/ros1/records.h": c_records,
               "c++/uwrosv2/abb/ros1/records.hpp": cpp_records,
               "rust/ros1/records.rs": rust_records}
    for path, render in outputs.items():
        content = render(records, hashes, minimum)
        target = PUBLIC / path
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.is_file() or content != target.read_text():
            target.write_text(content)


if __name__ == "__main__":
    main()
