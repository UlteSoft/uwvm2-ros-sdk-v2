import * as observation from "uwrosv2/platform/agibot/observation";

/* Constructed from the pinned upstream wire definition. */
const sample = new Uint8Array([
    0x00, 0x01, 0x00, 0x00, 0x06, 0x00, 0x00, 0x00, 0x66, 0x72, 0x61, 0x6d,
    0x65, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0xe0, 0x3f, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xd0, 0xbf,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xfc, 0x3f, 0x01, 0x01
]);

const bigEndian = new Uint8Array([
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x06, 0x66, 0x72, 0x61, 0x6d,
    0x65, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x3f, 0xe0, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0xbf, 0xd0, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x3f, 0xfc, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x01
]);

function check(data) {
    if (observation.read_position(data) !== 0.5) throw Error("position");
    if (observation.read_position(data.subarray(0, data.length - 1)) !== undefined) throw Error("truncated position");
    if (observation.read_velocity(data) !== -0.25) throw Error("velocity");
    if (observation.read_velocity(data.subarray(0, data.length - 1)) !== undefined) throw Error("truncated velocity");
    if (observation.read_effort(data) !== 1.75) throw Error("effort");
    if (observation.read_effort(data.subarray(0, data.length - 1)) !== undefined) throw Error("truncated effort");
    if (observation.read_error_code(data) !== 257) throw Error("error_code");
    if (observation.read_error_code(data.subarray(0, data.length - 1)) !== undefined) throw Error("truncated error_code");
}

check(sample);
check(bigEndian);
