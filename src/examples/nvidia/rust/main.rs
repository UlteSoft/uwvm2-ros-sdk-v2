#![no_std]
#[cfg(target_arch = "wasm32")]
use core::arch::wasm32::unreachable;
#[cfg(target_arch = "wasm64")]
use wros_runtime::abort as unreachable;
use core::{hint::black_box, panic::PanicInfo};
use wros_observation::*;

#[panic_handler]
fn panic(_: &PanicInfo) -> ! { unreachable() }

// Constructed wire examples for the pinned upstream definition.
const EXAMPLE: &[u8] = &[
    0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x06, 0x00, 0x00, 0x00, 0x66, 0x72, 0x61, 0x6d, 0x65, 0x00, 0x00, 0x00,
    0x78, 0x56, 0x34, 0x12, 0xb1, 0xcb, 0x74, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x05, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00
];

const BIG_ENDIAN: &[u8] = &[
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x06, 0x66, 0x72, 0x61, 0x6d, 0x65, 0x00, 0x00, 0x00,
    0x12, 0x34, 0x56, 0x78, 0x00, 0x74, 0xcb, 0xb1, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x05
];

fn check(data: &[u8]) {
    if read_left_ticks(data) != Some(305419896) || read_left_ticks(&data[..data.len() - 1]).is_some() { unreachable() }
    if read_right_ticks(data) != Some(7654321) || read_right_ticks(&data[..data.len() - 1]).is_some() { unreachable() }
    if read_encoder_timestamp(data) != Some(4294967301) || read_encoder_timestamp(&data[..data.len() - 1]).is_some() { unreachable() }
}

#[no_mangle]
pub extern "C" fn _start() {
    check(black_box(EXAMPLE));
    check(black_box(BIG_ENDIAN));
}
