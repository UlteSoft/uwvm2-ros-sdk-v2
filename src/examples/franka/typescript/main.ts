function check(data: Uint8Array): void {
    if (observation.read_position(data, 1) !== -1.0) throw Error("position");
    if (observation.read_position(data.subarray(0, data.length - 1), 1) !== undefined) throw Error("truncated position");
    if (observation.read_position(data, -1) !== undefined) throw Error("invalid index");
    if (observation.read_desired_position(data, 1) !== 1.0) throw Error("desired_position");
    if (observation.read_desired_position(data.subarray(0, data.length - 1), 1) !== undefined) throw Error("truncated desired_position");
    if (observation.read_desired_position(data, -1) !== undefined) throw Error("invalid index");
    if (observation.read_commanded_position(data, 1) !== -1.0) throw Error("commanded_position");
    if (observation.read_commanded_position(data.subarray(0, data.length - 1), 1) !== undefined) throw Error("truncated commanded_position");
    if (observation.read_commanded_position(data, -1) !== undefined) throw Error("invalid index");
    if (observation.read_commanded_velocity(data, 1) !== -0.0625) throw Error("commanded_velocity");
    if (observation.read_commanded_velocity(data.subarray(0, data.length - 1), 1) !== undefined) throw Error("truncated commanded_velocity");
    if (observation.read_commanded_velocity(data, -1) !== undefined) throw Error("invalid index");
    if (observation.read_commanded_acceleration(data, 1) !== -0.25) throw Error("commanded_acceleration");
    if (observation.read_commanded_acceleration(data.subarray(0, data.length - 1), 1) !== undefined) throw Error("truncated commanded_acceleration");
    if (observation.read_commanded_acceleration(data, -1) !== undefined) throw Error("invalid index");
}

