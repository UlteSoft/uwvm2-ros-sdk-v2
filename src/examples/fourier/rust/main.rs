fn check(data: &[u8]) {
    if read_timestamp(data) != Some(4294967302) || read_timestamp(&data[..data.len() - 1]).is_some() { unreachable() }
    if read_q(data, 1) != Some(-0.125) || read_q(&data[..data.len() - 1], 1).is_some() { unreachable() }
    if read_q(data, usize::MAX).is_some() { unreachable() }
    if read_q_dot(data, 1) != Some(0.5) || read_q_dot(&data[..data.len() - 1], 1).is_some() { unreachable() }
    if read_q_dot(data, usize::MAX).is_some() { unreachable() }
    if read_lf_touch(data) != Some(0.25) || read_lf_touch(&data[..data.len() - 1]).is_some() { unreachable() }
    if read_rf_touch(data) != Some(0.75) || read_rf_touch(&data[..data.len() - 1]).is_some() { unreachable() }
}

