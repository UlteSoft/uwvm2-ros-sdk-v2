function check(data: Uint8Array): void {
    if (observation.read_timestamp(data) !== 4294967302n) throw Error("timestamp");
    if (observation.read_timestamp(data.subarray(0, data.length - 1)) !== undefined) throw Error("truncated timestamp");
    if (observation.read_q(data, 1) !== -0.125) throw Error("q");
    if (observation.read_q(data.subarray(0, data.length - 1), 1) !== undefined) throw Error("truncated q");
    if (observation.read_q(data, -1) !== undefined) throw Error("invalid index");
    if (observation.read_q_dot(data, 1) !== 0.5) throw Error("q_dot");
    if (observation.read_q_dot(data.subarray(0, data.length - 1), 1) !== undefined) throw Error("truncated q_dot");
    if (observation.read_q_dot(data, -1) !== undefined) throw Error("invalid index");
    if (observation.read_lf_touch(data) !== 0.25) throw Error("lf_touch");
    if (observation.read_lf_touch(data.subarray(0, data.length - 1)) !== undefined) throw Error("truncated lf_touch");
    if (observation.read_rf_touch(data) !== 0.75) throw Error("rf_touch");
    if (observation.read_rf_touch(data.subarray(0, data.length - 1)) !== undefined) throw Error("truncated rf_touch");
}

