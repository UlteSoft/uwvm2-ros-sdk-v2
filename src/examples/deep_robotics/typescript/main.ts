import * as observation from "uwrosv2/platform/deep_robotics/observation";

/* Constructed from the pinned upstream wire definition. */
const sample = new Uint8Array([
    0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x80, 0x3e, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x40, 0xbf, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0xc0, 0x3f, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x18, 0x41
]);

const bigEndian = new Uint8Array([
    0x00, 0x00, 0x00, 0x00, 0x3e, 0x80, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0xbf, 0x40, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x3f, 0xc0, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x41, 0x18, 0x00, 0x00
]);

function check(data: Uint8Array): void {
    if (observation.read_roll(data) !== 0.25) throw Error("roll");
    if (observation.read_roll(data.subarray(0, data.length - 1)) !== undefined) throw Error("truncated roll");
    if (observation.read_yaw(data) !== -0.75) throw Error("yaw");
    if (observation.read_yaw(data.subarray(0, data.length - 1)) !== undefined) throw Error("truncated yaw");
    if (observation.read_omega_z(data) !== 1.5) throw Error("omega_z");
    if (observation.read_omega_z(data.subarray(0, data.length - 1)) !== undefined) throw Error("truncated omega_z");
    if (observation.read_acc_z(data) !== 9.5) throw Error("acc_z");
    if (observation.read_acc_z(data.subarray(0, data.length - 1)) !== undefined) throw Error("truncated acc_z");
}

check(sample);
check(bigEndian);
