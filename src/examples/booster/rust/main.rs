#![no_std]
#[cfg(target_arch = "wasm32")]
use core::arch::wasm32::unreachable;
#[cfg(target_arch = "wasm64")]
use wros_runtime::abort as unreachable;
use core::{hint::black_box, panic::PanicInfo};
use wros_observation::*;

#[panic_handler]
fn panic(_: &PanicInfo) -> ! { unreachable() }

// Constructed wire examples for the pinned upstream definition.
const EXAMPLE: &[u8] = &[
    0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x80, 0x3e,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xc0, 0xbf,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x1c, 0x41,
    0x00, 0x00, 0x00, 0x00
];

const BIG_ENDIAN: &[u8] = &[
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x3e, 0x80, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xbf, 0xc0, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x41, 0x1c, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00
];

fn check(data: &[u8]) {
    if read_rpy(data, 1) != Some(0.25) || read_rpy(&data[..data.len() - 1], 1).is_some() { unreachable() }
    if read_rpy(data, usize::MAX).is_some() { unreachable() }
    if read_gyro(data, 1) != Some(-1.5) || read_gyro(&data[..data.len() - 1], 1).is_some() { unreachable() }
    if read_gyro(data, usize::MAX).is_some() { unreachable() }
    if read_acc(data, 1) != Some(9.75) || read_acc(&data[..data.len() - 1], 1).is_some() { unreachable() }
    if read_acc(data, usize::MAX).is_some() { unreachable() }
}

#[no_mangle]
pub extern "C" fn _start() {
    check(black_box(EXAMPLE));
    check(black_box(BIG_ENDIAN));
}
