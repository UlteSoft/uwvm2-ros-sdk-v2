"""Generate the public Go declarations from the VM's registered signatures."""
import json
from pathlib import Path
import sys
import subprocess
import textwrap

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "src/abi"))
from language_contract import authority, domains, memory_contract, parameters, result_text

OUTPUT = ROOT / "include/u2rosv2/universal/go"
INITIALISMS = {"abi": "ABI", "io": "IO", "qos": "QoS", "ros": "ROS", "vm": "VM"}


def go_name(name):
    return "".join(INITIALISMS.get(part, part.capitalize()) for part in name.replace(".", "_").split("_"))


def comment(paragraphs):
    lines = []
    for para in paragraphs:
        if lines:
            lines.append("//")
        lines.extend("// " + line for line in textwrap.wrap(para, 91, break_long_words=False, break_on_hyphens=False))
    return lines


def main():
    contract = json.loads((ROOT / "src/abi/contract.json").read_bytes())
    for domain, rows in domains(contract).items():
        lines = ["// Code generated by src/compilers/go/generate_abi.py. DO NOT EDIT.",
                 "//go:build wasm || (tinygo && tinygo.wasm)", "", "package u2rosv2", ""]
        for row in rows:
            signature = row["wasm_signature"]
            values = row["parameters"]
            if signature["parameters"] != [p["type"] for p in values] or signature["results"] != ["i32"]:
                raise ValueError("unrepresentable signature for " + row["name"])
            name = go_name(row["name"])
            params = parameters(row)
            docs = [f"{name} calls {row['name']}. {row['contract']}", authority(row), memory_contract(row)]
            docs.extend(f"{p['name']} ({p['type']}) — {params[p['name']]}" for p in values)
            docs.append(result_text(row))
            args = ", ".join(p["name"] + " uint" + p["type"][1:] for p in values)
            lines.extend([*comment(docs), "//", f"//go:wasmimport {contract['module']} {row['name']}",
                          f"func {name}({args}) uint32", ""])
        (OUTPUT / (domain + ".go")).write_bytes(subprocess.check_output(["gofmt"], input="\n".join(lines).encode()))
    status = ["// Code generated by src/compilers/go/generate_abi.py. DO NOT EDIT.", "",
              "package u2rosv2", "", "const ("]
    status.extend(f"\tStatus{go_name(key)} uint32 = {value}" for key, value in contract["statuses"].items())
    (OUTPUT / "status.go").write_bytes(subprocess.check_output(["gofmt"], input="\n".join([*status, ")", ""]).encode()))


if __name__ == "__main__":
    main()
