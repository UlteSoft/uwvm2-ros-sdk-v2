-- @file xmake.lua
-- @brief Build and test this platform's guest modules.
set_project("nvidia-groot-common-typescript")
includes(path.join(os.getenv("UWVM_ROS_SDK_ROOT"), "tools/xmake/ros.lua"))

target("common")
    set_kind("binary")
    set_language("typescript")
    set_ros_platform("nvidia-groot")
    set_wros_profile({core = "3.0", eh = true, mte = true})
    set_optimize("fastest")
    set_symbols("debug")
    add_wros_operations("abi")
    set_wros_typescript_entry("main.ts")
    set_wros_test_queries("abi", "realtime-clock")
    add_files("filter.ts", "main.ts")
    add_wros_tests("int", "aot")
target_end()

target("sensor")
    set_kind("binary")
    set_language("typescript")
    set_ros_platform("nvidia-groot")
    set_wros_profile({core = "3.0", eh = true, mte = true})
    set_optimize("fastest")
    set_symbols("debug")
    set_wros_test_queries("realtime-clock")
    add_files("sensor.ts")
    add_wros_tests("int", "aot")
target_end()
